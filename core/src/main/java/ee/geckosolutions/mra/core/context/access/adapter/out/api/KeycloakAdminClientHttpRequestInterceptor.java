package ee.geckosolutions.mra.core.context.access.adapter.out.api;

import java.io.IOException;

import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpRequest;
import org.springframework.http.client.ClientHttpRequestExecution;
import org.springframework.http.client.ClientHttpRequestInterceptor;
import org.springframework.http.client.ClientHttpResponse;
import org.springframework.stereotype.Component;

@Component
@RequiredArgsConstructor
public class KeycloakAdminClientHttpRequestInterceptor implements ClientHttpRequestInterceptor {

    private final KeycloakServiceAccountTokenProvider tokenProvider;

    @Override
    public ClientHttpResponse intercept(HttpRequest request, byte[] body, ClientHttpRequestExecution execution)
            throws IOException {
        request.getHeaders().setBearerAuth(tokenProvider.getAccessToken());
        return execution.execute(request, body);
    }

}
