CREATE ROLE core_liquibase WITH LOGIN PASSWORD 'core_liquibase-secret';
CREATE ROLE core WITH LOGIN PASSWORD 'core-secret';

CREATE DATABASE core OWNER core_liquibase;
REVOKE ALL ON DATABASE core FROM PUBLIC;
GRANT CONNECT ON DATABASE core TO core;

\connect core

CREATE SCHEMA liquibase AUTHORIZATION core_liquibase;

ALTER SCHEMA public OWNER TO core_liquibase;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO core;

ALTER DEFAULT PRIVILEGES FOR ROLE core_liquibase IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO core;
ALTER DEFAULT PRIVILEGES FOR ROLE core_liquibase IN SCHEMA public
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO core;
